
from pathlib import Path

import pandas as pd
import streamlit as st


# ==========================================
# NIH CHEST X-RAY EXPLORER
# ==========================================

DATA_FOLDER = Path("data/nih")
LABELS_FILE = DATA_FOLDER / "sample_labels.csv"
IMAGES_FOLDER = DATA_FOLDER / "images"


@st.cache_data
def load_xray_data():
    return pd.read_csv(LABELS_FILE)


def format_patient_age(value):
    """
    Convert NIH ages such as 060Y into 60 years.
    """
    try:
        age_text = str(value).strip().upper()
        age_text = age_text.replace("Y", "")
        age = int(age_text)
        return f"{age}"
    except (ValueError, TypeError):
        return "Unknown"


def show_xray_tab():

    st.header("NIH Chest X-ray Explorer")

    st.write(
        "Explore de-identified chest X-ray research "
        "images and their recorded findings."
    )

    st.info(
        "Research demonstration only. "
        "The labels come from the NIH dataset "
        "and are not diagnoses generated by ER Insight."
    )

    # ======================================
    # CHECK DATASET FILES
    # ======================================

    if not LABELS_FILE.exists():
        st.error("X-ray labels file was not found.")
        return

    if not IMAGES_FOLDER.exists():
        st.error("X-ray images folder was not found.")
        return

    # ======================================
    # LOAD DATASET
    # ======================================

    data = load_xray_data()

    required_columns = [
        "Image Index",
        "Finding Labels"
    ]

    for column in required_columns:
        if column not in data.columns:
            st.error(f"Missing column: {column}")
            return

    # Match metadata with actual image files
    image_files = {
        path.name: path
        for path in IMAGES_FOLDER.glob("*.png")
    }

    available = data[
        data["Image Index"].astype(str).isin(image_files)
    ].copy()

    st.metric(
        "Available X-ray Examples",
        f"{len(available):,}"
    )

    if available.empty:
        st.warning("No matching X-ray images found.")
        return

    # ======================================
    # PATIENT SELECTION
    # ======================================

    # Show the first 100 available records
    available = available.head(100)

    options = {}

    for _, row in available.iterrows():

        filename = str(row["Image Index"])

        patient_id = str(
            row.get("Patient ID", "Unknown")
        )

        # Format age in the dropdown
        age = format_patient_age(
            row.get("Patient Age")
        )

        options[filename] = (
            f"Patient #{patient_id} | "
            f"Age {age} | "
            f"X-ray {filename}"
        )

    selected = st.selectbox(
        "Select an X-ray Patient Record",
        options=list(options.keys()),
        format_func=lambda name: options[name]
    )

    record = available.loc[
        available["Image Index"] == selected
    ].iloc[0]

    st.divider()

    # ======================================
    # PATIENT INFORMATION
    # ======================================

    st.subheader("Patient Information")

    col1, col2, col3 = st.columns(3)

    # Format age in Patient Information
    
    col1.metric(
        "Patient Age",
        str(record["Patient Age"])
    )


    col2.metric(
        "Recorded Sex",
        str(record.get("Patient Gender", "Unknown"))
    )

    col3.metric(
        "X-ray View",
        str(record.get("View Position", "Unknown"))
    )

    st.write(
        "**De-identified Patient ID:**",
        record.get("Patient ID", "Unknown")
    )

    # ======================================
    # ACTUAL CHEST X-RAY
    # ======================================

    st.divider()

    st.subheader("Actual Chest X-ray")

    image_path = image_files[selected]

    st.image(
        str(image_path),
        caption=f"NIH Chest X-ray: {selected}",
        use_container_width=True
    )

    # ======================================
    # RECORDED FINDINGS
    # ======================================

    st.divider()

    st.subheader("Recorded Findings")

    st.caption(
        "These findings come from the NIH research "
        "dataset. They are not independently "
        "verified by ER Insight."
    )

    labels = str(
        record["Finding Labels"]
    ).split("|")

    for label in labels:

        label = label.strip()

        with st.container(border=True):

            st.markdown(
                f"#### {label.replace('_', ' ')}"
            )

            if label == "No Finding":

                st.write(
                    "The dataset contains no labeled "
                    "abnormal findings for this image. "
                    "This does not guarantee that "
                    "the examination is clinically normal."
                )

            else:

                st.write(
                    "This finding was recorded in "
                    "the original NIH research dataset."
                )

    # ======================================
    # PATIENT NOTES
    # ======================================

    st.divider()

    st.subheader("Patient Notes")

    st.write(
        "Enter fictional observations or "
        "additional comments about this X-ray."
    )

    note_key = f"xray_notes_{selected}"

    if note_key not in st.session_state:
        st.session_state[note_key] = ""

    st.text_area(
        "Additional Notes",
        key=note_key,
        height=150,
        placeholder=(
            "Enter fictional patient observations "
            "or follow-up comments..."
        )
    )

    st.caption(
        "Notes remain in the current Streamlit session. "
        "Do not enter real patient information."
    )

    # ======================================
    # ABOUT THE DATASET
    # ======================================

    st.divider()

    st.subheader("About the NIH Dataset")

    st.write(
        "The NIH ChestX-ray14 dataset contains "
        "112,120 chest X-ray images from "
        "30,805 de-identified patients."
    )

    st.write(
        "ER Insight uses a smaller sample "
        "to demonstrate how chest imaging "
        "and recorded findings can be organized "
        "for clinical research."
    )

    st.caption(
        "The original NIH labels were extracted "
        "from radiology reports using automated "
        "methods and may contain errors."
    )

    st.markdown(
        "[Original NIH Chest X-ray Dataset]"
        "(https://huggingface.co/datasets/"
        "alkzar90/NIH-Chest-X-ray-dataset)"
    )
